def test_markdown_tables_headings_and_bold_become_feishu_elements():
    text = ("# 标题\n正文 **重点** 和 *斜体*\n- 第一条\n* 第二条\n\n| 店铺 | 花费 |\n|:---|---:|\n| **川页** | $3,217.70 |\n"
            "| Campx |\n\n---\n```\n代码 `x`\n```\n> 引用")
    elements = cards.markdown_elements(text)
    assert [element["tag"] for element in elements] == ["markdown", "table", "hr", "markdown"]
    assert elements[0]["content"] == "**标题**\n正文 **重点** 和 ＊斜体＊\n- 第一条\n- 第二条"
    table = elements[1]
    assert [column["display_name"] for column in table["columns"]] == ["店铺", "花费"]
    assert table["rows"] == [{"c0": "川页", "c1": "$3,217.70"}, {"c0": "Campx", "c1": "—"}]
    assert "代码 ｀x｀" in elements[3]["content"] and "引用" in elements[3]["content"]


def test_model_output_cannot_inject_mentions_links_or_html():
    text = "看 [这里](https://evil.example) <at id=ou_x></at> <at id=all></at> www.evil.example\n| a |\n|---|\n| <b>x</b> |"
    elements = cards.markdown_elements(text)
    content = json.dumps(elements, ensure_ascii=False)
    assert "<at" not in content and "](" not in content and "https://" not in content and "<b>" not in content
    assert "这里" in elements[0]["content"]


def test_long_reports_are_split_within_the_five_table_limit():
    section = "| 店铺 | 花费 |\n|---|---|\n" + "\n".join(f"| 店铺{i} | ${i} |" for i in range(20))
    text = "\n\n".join(f"**第 {i} 节**\n{section}" for i in range(8))
    values = cards.report_cards("广告日报 · 2026-11-22", text)
    assert len(values) == 2 and all(card_fits(value) for value in values)
    assert values[0]["header"]["title"]["content"] == "广告日报 · 2026-11-22（1/2）"
    assert sum(element["tag"] == "table" for value in values for element in value["body"]["elements"]) == 8
    # Owner (Nov 2026): no footer about where the data came from or how it was analyzed.
    assert values[-1]["body"]["elements"][-1]["tag"] == "table"


def test_tables_keep_at_most_sixty_rows():
    text = "| 店铺 |\n|---|\n" + "\n".join(f"| s{i} |" for i in range(75))
    elements = cards.markdown_elements(text)
    assert len(elements[0]["rows"]) == 60 and elements[1]["content"] == "另有 15 行未展开。"


def test_hourly_card_groups_findings_and_names_operators_in_the_last_column():
    value = cards.hourly_card(HOURLY_FINDINGS, day="2026-11-23", time="22:05", names={"101": "香港川页", "102": "Campx"},
                              operators={"101": "未映射运营", "102": "高爽"})
    text = plain_text(value)
    assert value["header"]["title"]["content"] == "广告实时监控 · 美西 2026-11-23 22:05"
    assert value["header"]["template"] == "red"
    assert value["body"]["elements"][0]["content"] == "2 个店铺 3 个广告活动触发提醒。"
    assert "店铺 | 广告活动 | 花费 | 点击 | 广告订单 | ACOS | CVR | 建议 | 运营" in text
    assert "**高花费无转化（1）**" in text and "低花费高转化（1）" in text
    assert "Campx | Campaign 9001 | $41.20 | 28 | 0 | — | 0.0% | 先看今日搜索词 | 高爽" in text
    # Only the alerts: no data source, rule explanation or "generated by" line.
    assert not any(word in text for word in ("SparkX", "DeepSeek", "判定", "归因", "只读"))
    assert value["body"]["elements"][-1]["tag"] == "table"
    assert cards.hourly_card([], day="d", time="t", names={}, operators={}) is None


def test_the_operator_column_always_comes_last():
    elements = cards.markdown_elements("| 店铺 | 运营 | 花费 |\n|---|---|---|\n| Campx | 高爽 | $41 |\n| 川页 | 未映射运营 |")
    table = elements[0]
    assert [column["display_name"] for column in table["columns"]] == ["店铺", "花费", "运营"]
    assert table["rows"] == [{"c0": "Campx", "c1": "$41", "c2": "高爽"}, {"c0": "川页", "c1": "—", "c2": "未映射运营"}]
    wide = ["运营"] + [f"列{i}" for i in range(20)]
    order = cards.column_order(wide)
    assert len(order) == cards.MAX_COLUMNS and order[-1] == 0  # trimming never drops the operator
    assert cards.column_order(["店铺", "负责运营", "花费"]) == [0, 2, 1]
    assert cards.column_order(["店铺", "运营情况"]) == [0, 1]  # only an operator column moves


def test_test_copies_are_marked_and_keep_the_mention_reserve():
    values = cards.report_cards("广告日报 · 2026-11-22", "**全公司核心指标**\n正文")
    marked = cards.mark_as_test(values)
    assert marked[0]["header"]["title"]["content"] == "【测试】广告日报 · 2026-11-22"
    assert marked[0]["body"] == values[0]["body"]  # the same content, only the title is marked
    assert values[0]["header"]["title"]["content"] == "广告日报 · 2026-11-22"  # the preview itself is unchanged
    assert card_fits(marked[0], cards.MENTION_RESERVE)


def test_the_mention_line_names_each_operators_stores_safely():
    card = cards.report_cards("复盘", "正文")[0]
    sent = with_mentions(card, ["ou_a", "ou_b"], {"ou_a": "Campx、香港川页", "ou_b": "[x](https://evil.example) <at id=all>"})
    line = sent["body"]["elements"][0]["content"]
    assert line.startswith("对应运营：<at id=ou_a></at>（Campx、香港川页） <at id=ou_b></at>（")
    assert "https://" not in line and "<at id=all>" not in line and line.count("<at ") == 2
    crowded = {f"ou_{i}": "很长的店铺名称" * 8 for i in range(40)}
    assert mention_line(list(crowded), crowded) == "对应运营：" + " ".join(f"<at id={uid}></at>" for uid in crowded)
    assert with_mentions(card, [])["body"]["elements"] == card["body"]["elements"]
